-- ============================================================
-- 01-create-user.sql
-- Creates the MERIDIAN application user in FREEPDB1
-- Run as SYSTEM / SYSDBA
-- ============================================================

ALTER SESSION SET CONTAINER = FREEPDB1;

-- Drop user if exists (for re-runs)
BEGIN
    EXECUTE IMMEDIATE 'DROP USER MERIDIAN CASCADE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1918 THEN RAISE; END IF;
END;
/

-- Create application user
CREATE USER MERIDIAN IDENTIFIED BY MeridianBank2026
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON USERS;

-- Grant required privileges
GRANT CONNECT, RESOURCE TO MERIDIAN;
GRANT CREATE SESSION TO MERIDIAN;
GRANT CREATE TABLE TO MERIDIAN;
GRANT CREATE VIEW TO MERIDIAN;
GRANT CREATE SEQUENCE TO MERIDIAN;
GRANT CREATE PROCEDURE TO MERIDIAN;
GRANT CREATE TRIGGER TO MERIDIAN;
GRANT CREATE TYPE TO MERIDIAN;
GRANT CREATE JOB TO MERIDIAN;

-- Oracle Text privilege (for CONTEXT index)
GRANT CTXAPP TO MERIDIAN;

-- Oracle Spatial privileges
-- USER_SDO_GEOM_METADATA is a per-user view; MERIDIAN can insert into
-- its own view by default. Grant SELECT on the underlying metadata table.
GRANT SELECT ON MDSYS.SDO_GEOM_METADATA_TABLE TO MERIDIAN;
GRANT CREATE INDEX TO MERIDIAN;

-- Oracle Advanced Queuing privileges
GRANT AQ_ADMINISTRATOR_ROLE TO MERIDIAN;
GRANT AQ_USER_ROLE TO MERIDIAN;
GRANT EXECUTE ON SYS.DBMS_AQ TO MERIDIAN;
GRANT EXECUTE ON SYS.DBMS_AQADM TO MERIDIAN;

-- DBMS_CRYPTO for SSN encryption
GRANT EXECUTE ON SYS.DBMS_CRYPTO TO MERIDIAN;

-- DBMS_SCHEDULER for batch jobs
GRANT EXECUTE ON SYS.DBMS_SCHEDULER TO MERIDIAN;

COMMIT;
